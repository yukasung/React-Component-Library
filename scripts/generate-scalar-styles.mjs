import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import postcss from 'postcss'
import tailwind from '@tailwindcss/postcss'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const scope = ':where(.rc-scalar, .rc-scalar *)'
// Compile separately from consumer CSS: no app scanning, Preflight, theme
// variables or property registrations can escape into the host application.
const sources = ['InputNumber/InputNumber.tsx', 'InputDate/InputDate.tsx', 'InputTime/InputTime.tsx', 'InputDateTime/InputDateTime.tsx', 'InputDateTime/styles.ts']
const theme = `
  --color-gray-50: #f9fafb; --color-gray-100: #f2f4f7;
  --color-gray-200: #e4e7ec; --color-gray-300: #d0d5dd;
  --color-gray-400: #98a2b3; --color-gray-500: #667085;
  --color-gray-600: #475467; --color-gray-700: #344054;
  --color-gray-800: #1d2939; --color-gray-900: #101828;
  --color-brand-300: #9cb9ff; --color-brand-500: #465fff;
  --shadow-theme-xs: 0px 1px 2px 0px rgba(16, 24, 40, 0.05);
`
const result = await postcss([tailwind({ optimize: false, base: root })]).process(`
@import "tailwindcss/theme" theme(inline);
@tailwind utilities source(none);
${sources.map((path) => `@source "./components/${path}";`).join('\n')}
@custom-variant dark (&:is(.dark *));
@theme inline { ${theme} }
`, { from: resolve(root, 'src/scalar-source.css') })
const defaults = postcss.rule({ selector: `${scope}, ${scope}::before, ${scope}::after` })
// Tailwind normally uses global, non-inheriting @property registrations.
// Explicit per-element defaults provide that isolation without registering
// those names globally (including variables whose initial value is invalid).
result.root.walkAtRules('property', (rule) => {
  const initial = rule.nodes.find((node) => node.prop === 'initial-value')
  defaults.append({ prop: rule.params, value: initial?.value ?? 'initial' })
  rule.remove()
})
result.root.walkAtRules('layer', (rule) => {
  if (rule.params === 'properties') rule.remove()
})
result.root.walkRules((rule) => {
  // Nested variant selectors already inherit the scoped outer rule.
  for (let parent = rule.parent; parent; parent = parent.parent) {
    if (parent.type === 'rule') return
  }
  rule.selectors = rule.selectors.map((selector) => `${scope}${selector}`)
})
// Flatpickr creates these nodes inside the scalar root. Keep its vendor
// selectors (including generic .dayContainer/.numInputWrapper) local too.
for (const path of ['node_modules/flatpickr/dist/flatpickr.css', 'src/components/InputDate/flatpickr-theme.css']) {
  const calendar = postcss.parse(readFileSync(resolve(root, path), 'utf8'))
  calendar.walkRules((rule) => {
    if (rule.parent.type === 'atrule' && rule.parent.name.endsWith('keyframes')) return
    rule.selectors = rule.selectors.map((selector) => {
      // Keep terminal pseudo-elements outside :is(), including vendor input
      // controls and legacy :before/:after spellings used by Flatpickr.
      const pseudo = selector.match(/(::[a-z-]+|:(?:before|after))$/)?.[0] ?? ''
      const element = pseudo ? selector.slice(0, -pseudo.length) : selector
      return `${scope}:is(${element})${pseudo}`
    })
  })
  result.root.append(calendar.nodes)
}
result.root.walkComments((comment) => { if (!comment.text.startsWith('!')) comment.remove() })
result.root.prepend(defaults)
const reset = `
/* Generated by scripts/generate-scalar-styles.mjs. Do not edit directly.
   Only these four controls and their popup descendants receive utilities. */
${scope}, ${scope}::before, ${scope}::after { box-sizing: border-box; border: 0 solid; }
.rc-scalar { font-family: inherit; line-height: 1.5; }
${scope}:is(input, button, select) { font: inherit; letter-spacing: inherit; color: inherit; margin: 0; padding: 0; background: transparent; }
${scope}:is(button) { appearance: button; }
${scope}:is(svg) { display: block; vertical-align: middle; }
`
const output = '@layer theme, base, components, utilities;\n@layer components {\n' + reset + result.root.toString() + '\n}\n'
const target = resolve(root, 'src/scalar-utilities.css')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Scalar styles are stale; run npm run generate:styles')
} else {
  writeFileSync(target, output)
}
